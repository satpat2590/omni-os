"""Local RPC for the two native applications. Uses the current install's private cluster."""
import contextlib
import fcntl
import json
import os
import re
import subprocess
import sys
from pathlib import Path

import classifier
from local import ROOT, STATE, PG, REGISTRY, preflight, cluster, runtime_env

SETTINGS = STATE / "desktop-settings.json"


def save(path, value):
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(value, indent=2))
    tmp.replace(path)


def tree(tasks, tags, links):
    roots = {c: dict(id=c, title=c.title(), children=[]) for c in ("physical","mental","financial","social")}
    nodes = {t["id"]: dict(id="tag-"+str(t["id"]),title=t["name"],children=[]) for t in tags}
    for t in tags:
        parent = nodes.get(t["parent_tag_id"]) or roots.get(t["category"])
        if parent:
            parent["children"].append(nodes[t["id"]])
    by_task = {}
    for link in links:
        by_task.setdefault(link["task_id"], []).append(link["tag_id"])
    for t in tasks:
        if t["category"] == "unclassified" and "unclassified" not in roots:
            roots["unclassified"] = dict(id="unclassified", title="Unclassified", children=[])
        parents = [nodes[i] for i in by_task.get(t["id"], []) if i in nodes] or [roots.get(t["category"])]
        for parent in filter(None, parents):
            parent["children"].append(dict(id=f"{parent['id']}-task-{t['id']}",title=t["title"],points=t["points"]))
    return list(roots.values())


def operation(action, data):
    os.environ.update(runtime_env())
    _, bindir = preflight()
    running = subprocess.run([bindir/"pg_ctl","-D",PG,"status"],stdout=subprocess.DEVNULL).returncode == 0
    cfg = json.loads(SETTINGS.read_text()) if SETTINGS.exists() else {"autoStart":True}
    registry = json.loads(REGISTRY.read_text()) if REGISTRY.exists() else {
        "version":1,"harnesses":{"script":{"kind":"script"}},"domains":{"atma":{"workdir":str(ROOT)}},"jobs":{}}
    # Retire only the exact demo job generated by the previous local installer.
    demo = {"domain":"atma","harness":"script","command":[str(STATE/"base/bin/python"),str(ROOT/"mindmap.py")]}
    if registry["jobs"].get("mindmap") == demo:
        del registry["jobs"]["mindmap"]
        save(REGISTRY, registry)
    if action=="classifierSave":
        classifier.configure(data)
    if action=="classify":
        if not running:
            raise ValueError("Start Omni first.")
        subprocess.Popen([sys.executable,str(ROOT/"scripts/classifier.py"),"manual"],
                         stdin=subprocess.DEVNULL,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL,start_new_session=True)
    if action == "autoStart":
        cfg["autoStart"] = bool(data["enabled"])
        save(SETTINGS, cfg)
    if action in ("start","startAtma") or (action == "openAtma" and cfg["autoStart"]):
        if not running:
            cluster(bindir, os.environ.copy())
            running = True
    if action == "stop" and running:
        with (STATE/"jobs.lock").open("a") as guard:
            try:
                fcntl.flock(guard,fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError:
                raise ValueError("An automation is running. Stop Omni after it finishes.")
            subprocess.run([bindir/"pg_ctl","-w","-D",PG,"stop"],check=True)
        running = False
    if action in ("domain","job","enable","run","removeJob","removeDomain"):
        name = data["name"].strip()
        if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9 _.-]{0,59}",name):
            raise ValueError("Use a name of 1–60 letters, numbers, spaces, dots, underscores or dashes.")
        if action == "domain":
            if name in registry["domains"]:
                raise ValueError("That domain already exists.")
            registry["domains"][name] = {"workdir":str(ROOT)}
        if action == "job":
            path = Path(data["path"])
            if name in registry["jobs"] or data["domain"] not in registry["domains"]:
                raise ValueError("Choose a unique automation name and an existing domain.")
            if not path.is_absolute() or not path.is_file() or not os.access(path,os.X_OK):
                raise ValueError("Choose an executable file.")
            registry["jobs"][name] = {"domain":data["domain"],"harness":"script","command":[str(path)],"workdir":str(path.parent),"enabled":True}
        if action == "removeJob":
            del registry["jobs"][name]
        if action == "removeDomain":
            if name == "atma" or any(job["domain"] == name for job in registry["jobs"].values()):
                raise ValueError("Only empty custom domains can be removed.")
            del registry["domains"][name]
        if action == "enable":
            registry["jobs"][name]["enabled"] = bool(data["enabled"])
        save(REGISTRY,registry)
        if action == "run":
            if not running:
                raise ValueError("Start Omni first.")
            if not registry["jobs"][name].get("enabled",True):
                raise ValueError("Enable this automation first.")
            with (STATE/"jobs.lock").open("a") as guard, (STATE/"automations.log").open("ab") as log:
                fcntl.flock(guard,fcntl.LOCK_SH)
                subprocess.Popen([STATE/"base/bin/omni","--registry",REGISTRY,"run",name], stdout=log,
                                 stderr=log,stdin=subprocess.DEVNULL,start_new_session=True,pass_fds=(guard.fileno(),))
    platform = {"classifier":classifier.public(),"running":running,"autoStart":cfg["autoStart"],"domains":sorted(registry["domains"]),
                "jobs":[dict(name=k,domain=v["domain"],enabled=v.get("enabled",True)) for k,v in registry["jobs"].items()]}
    if not running or action not in ("openAtma","startAtma","tasks","add","edit","complete","archive"):
        if running and platform["jobs"]:
            import psycopg2
            conn = psycopg2.connect("dbname=omni")
            try:
                with conn.cursor() as cur:
                    cur.execute("select distinct on (job) job,status from core.runs order by job,id desc")
                    states = dict(cur.fetchall())
                for job in platform["jobs"]:
                    job["status"] = states.get(job["name"],"Never run")
            finally:
                conn.close()
        return platform
    sys.path.insert(0,str(ROOT/"atma/api"))
    from utils import governance
    from utils.data import TaskCreate
    from utils.db import db
    from main import complete_task_record
    if action in ("add","edit") and not data["title"].strip():
        raise ValueError("Enter a task title.")
    if action == "add":
        governance.create(TaskCreate(title=data["title"].strip()),1,1)
    elif action in ("edit","complete","archive"):
        tid = int(data["id"])
        if not db.query("select id from tasks where id=%s and is_active and (assigned_to=1 or assigned_to is null)",(tid,)):
            raise ValueError("This task is no longer active.")
        if action == "complete":
            complete_task_record(tid,None)
        elif action == "edit":
            db.query("update tasks set title=%s where id=%s",(data["title"].strip(),tid))
        else:
            db.query("update tasks set is_active=false where id=%s",(tid,))
    tasks = db.query("""select t.id,t.title,t.category,t.is_active,coalesce(sum(c.points),0)::int points
        from tasks t left join task_completions c on c.task_id=t.id
        where t.assigned_to=1 or t.assigned_to is null group by t.id order by t.id desc""")
    tags = db.query("select id,parent_tag_id,name,category from tags order by name,id")
    links = db.query("select task_id,tag_id from task_tags")
    return dict(platform,tasks=tasks,tree=tree(tasks,tags,links))


if __name__ == "__main__":
    output = os.fdopen(os.dup(sys.stdout.fileno()), "w")
    os.dup2(sys.stderr.fileno(),sys.stdout.fileno())
    try:
        os.umask(0o077)
        with (STATE/"desktop.lock").open("a") as lock, contextlib.redirect_stdout(sys.stderr):
            fcntl.flock(lock,fcntl.LOCK_EX)
            result = operation(sys.argv[1],json.load(sys.stdin))
        print(json.dumps(result),file=output,flush=True)
    except Exception as exc:
        print(json.dumps({"error":str(exc)}),file=output,flush=True)
        sys.exit(1)
